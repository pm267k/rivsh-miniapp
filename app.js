function собрать(массив,поле){
  var о={}; массив.forEach(function(x){ if(x[поле]) о[x[поле]]=(о[x[поле]]||0)+1; });
  return Object.keys(о).sort(function(a,b){return о[b]-о[a];});
}
/* порядок как в таблице, без повторов */
function поПорядку(массив,поле){
  var о={}, пор=[]; массив.forEach(function(x){ if(x[поле]&&!о[x[поле]]){ о[x[поле]]=1; пор.push(x[поле]); } });
  return пор;
}
/* заголовки блоков в таблице набраны капсом — в чипе и метке это крик */
