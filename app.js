function фамилия(с){ return String(с||'').trim().split(/[\s·]+/)[0].toLowerCase(); }
/* поиск по словам в любом порядке и без разницы е/ё: «терапия хейс» найдёт «Терапию… Хейс» */
function норм(с){ return String(с||'').toLowerCase().replace(/ё/g,'е'); }
